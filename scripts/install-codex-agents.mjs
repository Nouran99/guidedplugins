#!/usr/bin/env node
// Installs the Codex subagent roles (TOML) of one or more plugins. Codex plugins cannot bundle subagents, so this copies them.
//   node scripts/install-codex-agents.mjs clean-code refactoring            # to $CODEX_HOME/agents (default ~/.codex/agents)
//   node scripts/install-codex-agents.mjs clean-code --project ~/work/app   # to ~/work/app/.codex/agents (trusted projects only)
//   node scripts/install-codex-agents.mjs clean-code --uninstall
// Flags: --dry-run (change nothing), --force (overwrite a role file that this project did not generate), --dest <dir>.
// Run it from a clone of the repository: it copies from dist/codex/<plugin>/skills/install-roles/roles, the same files the plugin's
// `$<plugin>:install-roles` skill copies. Needs Node 20 or later.
// Cost: Codex lists every role in the spawn tool's description (see docs/AGENTS_SUPPORT.md for the measured size).
// Install roles for the one to three books you use, not all fourteen.
import { codexRolesDir, codexRolesOf, fs, home, parseArgs, path, pickPlugins } from './install-lib.mjs';

const HEADER = 'Generated by scripts/build-targets.mjs';
const { flags, positional } = parseArgs(process.argv.slice(2), ['project', 'dest']);
const slugs = pickPlugins(positional);
const dest = flags.dest ?? (flags.project ? path.join(path.resolve(flags.project === true ? '.' : flags.project), '.codex', 'agents')
  : path.join(process.env.CODEX_HOME ?? path.join(home(), '.codex'), 'agents'));
const dry = !!flags['dry-run'];

let n = 0;
for (const slug of slugs) {
  const files = codexRolesOf(slug);
  for (const f of files) {
    const target = path.join(dest, f);
    if (flags.uninstall) {
      if (fs.existsSync(target) && fs.readFileSync(target, 'utf8').includes(HEADER)) { if (!dry) fs.rmSync(target); n++; }
      continue;
    }
    if (fs.existsSync(target) && !fs.readFileSync(target, 'utf8').includes(HEADER) && !flags.force) {
      console.error(`skip ${f}: exists and was not generated by this project (use --force to overwrite)`);
      continue;
    }
    if (!dry) { fs.mkdirSync(dest, { recursive: true }); fs.copyFileSync(path.join(codexRolesDir(slug), f), target); }
    n++;
  }
}
console.log(`${flags.uninstall ? 'removed' : 'installed'} ${n} role file(s) ${dry ? '(dry run) ' : ''}${flags.uninstall ? 'from' : 'into'} ${dest}`);
if (!flags.uninstall && n) console.log('Codex lists every installed role in each request, so install the books you use.');
