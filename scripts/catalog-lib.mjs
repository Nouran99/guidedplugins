// Renderers shared by gen-catalog.mjs (writes) and validate-plugin.mjs (checks the files are fresh).
import path from 'node:path';
import {
  componentInvocation, fullHeadings, norm, oneLine, readIf, sourceCitations, toList,
} from './lib.mjs';

export const README_START = '<!-- COMPONENTS:START -->';
export const README_END = '<!-- COMPONENTS:END -->';
export const GENERATED = '<!-- Generated by scripts/gen-catalog.mjs. Do not edit by hand. -->';

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function isManual(skill) { return skill.data?.['disable-model-invocation'] === true; }

export function counts(plugin) {
  const manual = plugin.skills.filter(isManual).length;
  return {
    skills: plugin.skills.length, manual, auto: plugin.skills.length - manual,
    agents: plugin.agents.length, styles: plugin.styles.length,
    total: plugin.skills.length + plugin.agents.length + plugin.styles.length,
  };
}

export function renderCatalogBlock(plugin) {
  const c = counts(plugin);
  const out = [];
  out.push(`**${c.total} components:** ${c.skills} skills (${c.auto} Claude can load on its own, ${c.manual} you run by name), ${c.agents} subagents, ${c.styles} output styles.`);
  out.push('');
  out.push('### Skills Claude loads on its own');
  out.push('');
  out.push('| Command | Use it when |');
  out.push('| --- | --- |');
  for (const s of plugin.skills.filter((x) => !isManual(x))) {
    out.push(`| \`${componentInvocation(plugin, s)}\` | ${esc(oneLine(s.data?.description, 220))} |`);
  }
  out.push('');
  out.push('### Skills you run by name');
  out.push('');
  out.push('| Command | What it does | Arguments |');
  out.push('| --- | --- | --- |');
  for (const s of plugin.skills.filter(isManual)) {
    out.push(`| \`${componentInvocation(plugin, s)}\` | ${esc(oneLine(s.data?.description, 220))} | ${s.data?.['argument-hint'] ? `\`${esc(s.data['argument-hint'])}\`` : ''} |`);
  }
  out.push('');
  out.push('### Subagents');
  out.push('');
  out.push('| Agent | Model | Access | Use it when |');
  out.push('| --- | --- | --- | --- |');
  for (const a of plugin.agents) {
    const tools = toList(a.data?.tools);
    const access = tools.some((t) => /^(Write|Edit)$/.test(t)) ? 'can edit files' : 'read-only';
    out.push(`| \`${componentInvocation(plugin, a)}\` | ${a.data?.model ?? ''} | ${access} | ${esc(oneLine(a.data?.description, 200))} |`);
  }
  out.push('');
  out.push('### Output styles (modes)');
  out.push('');
  out.push('| Style | What changes |');
  out.push('| --- | --- |');
  for (const s of plugin.styles) {
    out.push(`| \`${componentInvocation(plugin, s)}\` | ${esc(oneLine(s.data?.description, 220))} |`);
  }
  out.push('');
  return out.join('\n');
}

export function renderComponentsDoc(plugin) {
  const title = plugin.manifest?.displayName ?? plugin.slug;
  return `${GENERATED}\n# ${title}: component catalog\n\n${renderCatalogBlock(plugin)}`;
}

export function citationMap(plugin) {
  // normalized heading -> [component labels]
  const map = new Map();
  const all = [...plugin.skills, ...plugin.agents, ...plugin.styles];
  for (const c of all) {
    const cites = c.body ? sourceCitations(c.body) : null;
    if (!cites) continue;
    for (const cite of cites) {
      const k = norm(cite);
      if (!map.has(k)) map.set(k, []);
      map.get(k).push(`${c.kind}:${c.id}`);
    }
  }
  return map;
}

export function renderTraceabilityDoc(plugin) {
  const title = plugin.manifest?.displayName ?? plugin.slug;
  const full = readIf(path.join(plugin.dir, 'skills', 'principles', 'references', 'full.md')) ?? '';
  const { coverage } = fullHeadings(full);
  const map = citationMap(plugin);
  const out = [GENERATED, `# ${title}: traceability`, ''];
  out.push('Every section of the upstream *full* rule set (`skills/principles/references/full.md`) and the components that apply it. The validator fails when a section has no component.');
  out.push('');
  out.push('| Upstream section | Components |');
  out.push('| --- | --- |');
  let covered = 0;
  for (const h of coverage) {
    const comps = map.get(h.key) ?? [];
    if (comps.length) covered++;
    out.push(`| ${esc(h.raw)} | ${comps.length ? comps.map((x) => `\`${x}\``).join(', ') : '**NOT COVERED**'} |`);
  }
  out.push('');
  out.push(`Coverage: ${covered}/${coverage.length} sections.`);
  out.push('');
  return out.join('\n');
}

export function replaceReadmeBlock(readme, block) {
  const s = readme.indexOf(README_START);
  const e = readme.indexOf(README_END);
  if (s === -1 || e === -1 || e < s) return null;
  return `${readme.slice(0, s + README_START.length)}\n\n${block.trim()}\n\n${readme.slice(e)}`;
}

// ---------------------------------------------------------------- repo-level catalog
import { PLUGINS_DIR, REGISTRY, listPluginDirs, loadPlugin } from './lib.mjs';

export const CATALOG_START = '<!-- CATALOG:START -->';
export const CATALOG_END = '<!-- CATALOG:END -->';

export function loadedPlugins() {
  return listPluginDirs().map(loadPlugin).filter((p) => p.manifest);
}

export function buildMarketplace() {
  const mp = REGISTRY.marketplace;
  const order = new Map(REGISTRY.books.map((b, i) => [b.slug, i]));
  const plugins = loadedPlugins().sort((a, b) => (order.get(a.slug) ?? 99) - (order.get(b.slug) ?? 99)).map((p) => {
    const book = REGISTRY.books.find((b) => b.slug === p.slug);
    return {
      name: p.manifest.name,
      source: `./plugins/${p.slug}`,
      description: p.manifest.description,
      version: p.manifest.version,
      category: book?.category ?? 'engineering-practice',
      tags: p.manifest.keywords,
    };
  });
  return {
    name: mp.name,
    owner: { name: mp.owner },
    metadata: { description: mp.description, version: '1.0.0' },
    plugins,
  };
}

export function renderRootCatalog() {
  const order = new Map(REGISTRY.books.map((b, i) => [b.slug, i]));
  const rows = loadedPlugins().sort((a, b) => (order.get(a.slug) ?? 99) - (order.get(b.slug) ?? 99));
  const out = ['| Plugin | Book | Author | Components | Reach for it when |', '| --- | --- | --- | --- | --- |'];
  for (const p of rows) {
    const b = REGISTRY.books.find((x) => x.slug === p.slug);
    const c = counts(p);
    out.push(`| [\`${p.slug}\`](plugins/${p.slug}/README.md) | ${b.title} | ${b.bookAuthor} | ${c.total} (${c.skills} skills, ${c.agents} agents, ${c.styles} styles) | ${b.usefulWhen} |`);
  }
  out.push('');
  return out.join('\n');
}
