// OpenCode target (verified against opencode-ai 1.19 (V1) and @opencode/cli 2.0 (V2) in isolated installs).
//  dist/opencode/<plugin>/skills/<plugin>-<name>/   universal skills (OpenCode reads them from .opencode/skills, .agents/skills or skills.paths)
//  dist/opencode/<plugin>/agents/<plugin>-<name>.md subagents with an ENFORCED read-only permission map, and modes as primary agents
// OpenCode has no plugin marketplace; install with scripts/install-opencode.mjs or point skills.paths at the skills folder.
import {
  DIST, READ_ONLY_ALLOW, READ_ONLY_DENY, agentBodyFor, bt, cleanDir, copyFile, flat, modeName, path, rewrite, rewriteDescription, writeFile, yaml,
} from './core.mjs';
import { emitFlatSkills, flatDialect } from './agent-skills.mjs';

// OpenCode replaces its own system prompt with a primary agent's prompt, so say that the mode only changes the style of the answer.
const MODE_NOTE = 'This mode changes how you respond. It does not replace your normal coding, tool-use and safety conventions; keep following them.';

const dialect = () => flatDialect({ agentRead: (p, n) => `Load the ${bt(flat(p.slug, n))} skill with the skill tool` });

function agentFile({ description, mode, steps, readOnly, body }) {
  const l = ['---', `description: ${yaml(description)}`, `mode: ${mode}`];
  if (steps) l.push(`steps: ${steps}`);
  if (mode === 'subagent') {
    l.push('permission:');
    if (readOnly) {
      // OpenCode takes the LAST matching rule, so the catch-all comes first and the denies come after the allows
      l.push('  edit: deny', '  webfetch: deny', '  bash:', '    "*": deny', ...READ_ONLY_ALLOW.map((c) => `    ${yaml(c)}: allow`), ...READ_ONLY_DENY.map((c) => `    ${yaml(c)}: deny`));
    } else l.push('  webfetch: deny');
  }
  l.push('---', '');
  return `${l.join('\n')}${body}\n`;
}

export function buildOpenCode(model) {
  const out = path.join(DIST, 'opencode');
  cleanDir(out);
  const d = dialect();
  for (const plugin of model) {
    const root = path.join(out, plugin.slug);
    emitFlatSkills(plugin, path.join(root, 'skills'));
    const preloadLine = (skills) => `Before you start, load these skills with the skill tool: ${skills.map((n) => bt(flat(plugin.slug, n))).join(', ')}.`;
    for (const a of plugin.agents) {
      const body = agentBodyFor(plugin, a, d, { preloadLine });
      writeFile(path.join(root, 'agents', `${flat(plugin.slug, a.name)}.md`), agentFile({
        description: rewriteDescription(a.fm.description, plugin, d, { from: 'agent' }),
        mode: 'subagent', steps: a.fm.maxTurns, readOnly: a.readOnly, body,
      }));
    }
    for (const m of plugin.styles) {
      const name = flat(plugin.slug, modeName(m.name));
      writeFile(path.join(root, 'agents', `${name}.md`), agentFile({
        description: rewriteDescription(m.fm.description, plugin, d, { from: 'agent' }),
        mode: 'primary', body: `${MODE_NOTE}\n\n${rewrite(m.body.replace(/^\s+/, ''), plugin, d, { from: 'agent' })}`,
      }));
    }
    copyFile(path.join(plugin.dir, 'LICENSE'), path.join(root, 'LICENSE'));
    writeFile(path.join(root, 'NOTICE.md'), plugin.notice ?? '');
  }
  writeFile(path.join(out, 'README.md'), `# OpenCode build

Generated by scripts/build-targets.mjs from plugins/ in this repository. Do not edit by hand.

Per plugin: \`skills/\` (Agent Skills, ${'<plugin>-<name>'}), \`agents/\` (subagents whose edit and web-fetch tools are denied and whose shell is limited to a
read-only allowlist, plus each output style as a primary agent you switch to with Tab). Install with \`node scripts/install-opencode.mjs <plugin>\`
or point \`skills.paths\` at a plugin's \`skills/\` folder. See docs/AGENTS_SUPPORT.md.
`);
  return model;
}
