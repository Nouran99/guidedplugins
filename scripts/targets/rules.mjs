// Always-on rules as plain AGENTS.md snippets (read by Codex, OpenCode, Cursor, Copilot, Amp, Jules, Devin and most other agents;
// Gemini CLI reads them when context.fileName includes AGENTS.md). nano = tightest budget, mini = recommended working set.
// Compose several with scripts/compose-rules.mjs. The upstream rule text is copied verbatim.
import { DIST, cleanDir, flat, path, writeFile } from './core.mjs';

export function companionSection(plugin) {
  const f = (n) => `\`${n}\``;
  return `\n## Companion skills (if installed)\n\nThe ${plugin.book.title} rules above are backed by skills from the \`${plugin.slug}\` plugin. Use ${f('review')} to review a change, ${f('plan')} before a non-trivial change, ${f('explain-rule')} to look up a rule, ${f('checklist')} before finishing, and ${f('principles')} for the full rule set and routing table. Most agents name them \`${plugin.slug}-<skill>\` (for example \`${flat(plugin.slug, 'review')}\`); Codex mentions them as \`$${plugin.slug}:<skill>\` (for example \`$${plugin.slug}:review\`).\n`;
}

export function buildRules(model) {
  const out = path.join(DIST, 'rules');
  cleanDir(out);
  for (const plugin of model) {
    for (const size of ['nano', 'mini']) {
      const upstream = (plugin.refs[size] ?? '').replace(/\n+$/, '');
      writeFile(path.join(out, plugin.slug, `AGENTS.${size}.md`), `<!-- ${plugin.book.title}: ${size} rules from ciembor/agent-rules-books (MIT), packaged by guided-plugins/${plugin.slug} -->\n${upstream}\n${companionSection(plugin)}`);
    }
  }
  writeFile(path.join(out, 'README.md'), `# Always-on rules

Generated by scripts/build-targets.mjs from plugins/ in this repository. Do not edit by hand.

One folder per book with \`AGENTS.nano.md\` (smallest) and \`AGENTS.mini.md\` (recommended). Copy one into your project's \`AGENTS.md\`,
or compose several with \`node scripts/compose-rules.mjs <plugin>... --size nano --out AGENTS.md\`.
Keep one book as the always-on primary; load the others on demand through their skills. Codex caps the combined AGENTS.md chain at 32 KiB.
`);
  return model;
}
