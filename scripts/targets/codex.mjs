// OpenAI Codex CLI target (verified against codex-cli 0.162 in an isolated CODEX_HOME).
//  - dist/codex/<plugin>/            a Codex plugin: .codex-plugin/plugin.json + skills/<name>/ (Codex namespaces them <plugin>:<name>)
//  - dist/codex/agents/<plugin>-<name>.toml   custom subagents (Codex plugins cannot bundle agents; install with scripts/install-codex-agents.mjs)
//  - .agents/plugins/marketplace.json         marketplace Codex prefers over .claude-plugin/marketplace.json
import {
  DIST, MANUAL_SUFFIX, REGISTRY, ROOT, cleanDir, copyFile, flat, frontmatter, modeName, path, rewrite, writeFile,
} from './core.mjs';
import { skillDescription } from './agent-skills.mjs';

const bt = (s) => `\`${s}\``;
const mention = (p, n) => `$${p.slug}:${n}`; // explicit skill mention in Codex

export function codexDialect() {
  const hubRel = (ctx) => (ctx.skill === 'principles' ? '' : '../principles/');
  return {
    id: 'codex',
    argsLine: 'the text the user wrote together with this request (empty if none)',
    argsInline: 'the argument text',
    refSkill: (p, n) => mention(p, n),
    refAgent: (p, n) => flat(p.slug, n),
    refStyle: (p, n) => mention(p, modeName(n)),
    readSkill: (p, n, ctx, backticked) => {
      if (ctx.from === 'agent') return `Load the ${bt(mention(p, n))} skill`;
      const rel = ctx.from === 'doc' ? `../../${n}/SKILL.md` : `../${n}/SKILL.md`;
      return backticked ? `Read ${bt(rel)}` : `Read ${rel}`;
    },
    skillFile: (p, n, ctx) => {
      if (ctx.from === 'agent') return { phrase: `the ${bt(mention(p, n))} skill` };
      return { path: ctx.from === 'doc' ? `../../${n}/SKILL.md` : `../${n}/SKILL.md` };
    },
    skillsDir: (p, ctx) => (ctx.from === 'agent' ? { phrase: `the skills of the ${bt(p.slug)} plugin` } : { path: ctx.from === 'doc' ? '../../' : '../' }),
    refFile: (p, r, ctx) => {
      if (ctx.from === 'agent') return { phrase: `the ${bt(`references/${r}.md`)} file of the ${bt(mention(p, 'principles'))} skill` };
      if (ctx.from === 'doc') return { path: `${r}.md` };
      return { path: `${hubRel(ctx)}references/${r}.md` };
    },
    designFile: (p, ctx) => {
      if (ctx.from === 'agent') return { phrase: `the ${bt('references/design.md')} file of the ${bt(mention(p, 'principles'))} skill` };
      if (ctx.from === 'doc') return { path: 'design.md' };
      return { path: `${hubRel(ctx)}references/design.md` };
    },
  };
}

// TOML helpers --------------------------------------------------------------------------------------------
const tomlString = (s) => JSON.stringify(String(s)); // JSON basic strings are valid TOML basic strings
function tomlMultiline(s) {
  const text = String(s).replace(/\r\n/g, '\n').replace(/\n+$/, '');
  if (!text.includes("'''")) return `'''\n${text}\n'''`; // literal: no escaping needed
  return `"""\n${text.replace(/\\/g, '\\\\').replace(/"""/g, '""\\"')}\n"""`;
}

const READ_ONLY_NOTE = 'Operating constraint: this is a read-only role. Never create, edit, move or delete files and never run commands that change the repository or the system; inspect with read-only commands (git diff, git log, git show, git status, ls, grep) and report. Codex cannot enforce this for a subagent, so you are responsible for keeping to it.\n\n';

function agentToml(plugin, a, d) {
  const ctx = { from: 'agent' };
  const preload = (a.fm.skills ? [].concat(a.fm.skills) : []).map((n) => bt(mention(plugin, n)));
  let body = rewrite(a.body.replace(/^\s+/, ''), plugin, d, ctx);
  if (preload.length) body = `Before you start, load these skills: ${preload.join(', ')}.\n\n${body}`;
  if (a.readOnly) body = READ_ONLY_NOTE + body;
  return [
    `# ${'Generated by scripts/build-targets.mjs from plugins/'}${plugin.slug}/agents/${a.name}.md. Do not edit by hand.`,
    `name = ${tomlString(flat(plugin.slug, a.name))}`,
    `description = ${tomlString(rewrite(a.fm.description, plugin, d, ctx))}`,
    `developer_instructions = ${tomlMultiline(body)}`,
    '',
  ].join('\n');
}

function openaiYaml(display, short, prompt) {
  const y = (s) => JSON.stringify(s);
  return `interface:\n  display_name: ${y(display.slice(0, 64))}\n  short_description: ${y(short.slice(0, 1000))}\n  default_prompt: ${y(prompt.slice(0, 1000))}\npolicy:\n  allow_implicit_invocation: false\n`;
}

const title = (s) => s.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join(' ');

export function buildCodex(model) {
  const out = path.join(DIST, 'codex');
  cleanDir(out);
  const d = codexDialect();
  const mp = REGISTRY.marketplace;
  const entries = [];

  for (const plugin of model) {
    const root = path.join(out, plugin.slug);
    const rw = (t, ctx) => rewrite(t, plugin, d, ctx);
    const skillsRoot = path.join(root, 'skills');

    for (const s of plugin.skills) {
      const ctx = { from: 'skill', skill: s.name };
      const dir = path.join(skillsRoot, s.name);
      const fm = frontmatter({ name: s.name, description: skillDescription(rw(s.fm.description, ctx), s.manual) });
      writeFile(path.join(dir, 'SKILL.md'), fm + rw(s.body, ctx));
      for (const f of s.files) copyFile(path.join(s.dir, f), path.join(dir, f));
      if (s.manual) {
        writeFile(path.join(dir, 'agents', 'openai.yaml'),
          openaiYaml(title(s.name), rw(s.fm.description, ctx), `Use ${mention(plugin, s.name)}${s.fm['argument-hint'] ? ` on ${s.fm['argument-hint'].replace(/^\[|\]$/g, '')}` : ''}.`));
      }
    }
    if (plugin.design) writeFile(path.join(skillsRoot, 'principles', 'references', 'design.md'), rw(plugin.design, { from: 'doc' }));
    for (const m of plugin.styles) {
      const name = modeName(m.name);
      const ctx = { from: 'skill', skill: name };
      const dir = path.join(skillsRoot, name);
      writeFile(path.join(dir, 'SKILL.md'), frontmatter({ name, description: skillDescription(rw(m.fm.description, ctx), true) })
        + 'Adopt this mode for the rest of the session, until the user asks you to stop or to switch to another mode. It changes how you respond; it does not change what you are allowed to do.\n\n' + rw(m.body, ctx));
      writeFile(path.join(dir, 'agents', 'openai.yaml'), openaiYaml(`${title(m.name)} mode`, rw(m.fm.description, ctx), `Use ${mention(plugin, name)}.`));
    }

    for (const a of plugin.agents) writeFile(path.join(out, 'agents', `${flat(plugin.slug, a.name)}.toml`), agentToml(plugin, a, d));

    const man = plugin.manifest;
    writeFile(path.join(root, '.codex-plugin', 'plugin.json'), JSON.stringify({
      name: plugin.slug,
      version: man.version,
      description: man.description,
      author: man.author,
      homepage: man.homepage,
      repository: man.repository,
      license: 'MIT',
      keywords: man.keywords,
      skills: './skills/',
      interface: {
        displayName: plugin.book.title,
        shortDescription: plugin.book.usefulWhen.slice(0, 120),
        longDescription: man.description,
        developerName: man.author.name,
        category: 'Developer Tools',
        capabilities: ['Read', 'Write'],
        websiteURL: man.homepage,
        defaultPrompt: [
          `Review my changes with ${mention(plugin, 'review')}`.slice(0, 128),
          `Plan this change with ${mention(plugin, 'plan')}`.slice(0, 128),
          `Explain a rule with ${mention(plugin, 'explain-rule')}`.slice(0, 128),
        ],
      },
    }, null, 2));
    copyFile(path.join(plugin.dir, 'LICENSE'), path.join(root, 'LICENSE'));
    writeFile(path.join(root, 'NOTICE.md'), plugin.notice ?? '');
    writeFile(path.join(root, 'README.md'), `# ${plugin.book.title} for Codex

Generated by scripts/build-targets.mjs from plugins/${plugin.slug}/ in the guided-plugins repository.

- Skills: ${plugin.skills.length} workflow and rule skills plus ${plugin.styles.length} mode skills, invoked as \`$${plugin.slug}:<name>\` or from \`/skills\`.
- Subagents: ${plugin.agents.length} roles in \`../agents/${plugin.slug}-*.toml\`. Codex plugins cannot bundle subagents, so install them with \`node scripts/install-codex-agents.mjs ${plugin.slug}\`.
- Always-on rules: see \`../../rules/${plugin.slug}/\`.

Full instructions: docs/AGENTS_SUPPORT.md in the repository.
`);
    entries.push({
      name: plugin.slug,
      source: { source: 'local', path: `./dist/codex/${plugin.slug}` },
      policy: { installation: 'AVAILABLE', authentication: 'ON_INSTALL' },
      category: 'Developer Tools',
    });
  }

  writeFile(path.join(ROOT, '.agents', 'plugins', 'marketplace.json'), JSON.stringify({
    name: mp.name,
    interface: { displayName: 'Guided Plugins' },
    plugins: entries,
  }, null, 2));
  return model;
}
