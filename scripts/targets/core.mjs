// ------------------------------------------------------------------ model
function walk(dir, base = dir, out = []) {
  for (const e of listDir(dir)) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, base, out);
    else out.push(path.relative(base, p));
  }
  return out;
}

export function loadModel() {
  const order = new Map(REGISTRY.books.map((b, i) => [b.slug, i]));
  return listPluginDirs().map(loadPlugin).filter((p) => p.manifest)
    .sort((a, b) => (order.get(a.slug) ?? 99) - (order.get(b.slug) ?? 99))
    .map((p) => {
      const book = REGISTRY.books.find((b) => b.slug === p.slug);
      const refsDir = path.join(p.dir, 'skills', 'principles', 'references');
      const refs = {};
      for (const r of ['full', 'mini', 'nano']) refs[r] = readIf(path.join(refsDir, `${r}.md`));
      return {
        slug: p.slug, dir: p.dir, manifest: p.manifest, book, refs,
        design: readIf(path.join(p.dir, 'docs', 'DESIGN.md')),
        notice: readIf(path.join(p.dir, 'NOTICE.md')),
        skills: p.skills.map((s) => {
          const sdir = path.dirname(s.file);
          return {
            kind: 'skill', name: s.data.name, fm: s.data, body: s.body, manual: isManual(s), dir: sdir,
            files: walk(sdir).filter((f) => f !== 'SKILL.md'),
          };
        }),
        agents: p.agents.map((a) => ({ kind: 'agent', name: a.data.name, fm: a.data, body: a.body, tools: toList(a.data.tools), readOnly: !toList(a.data.tools).some((t) => /^(Write|Edit)$/.test(t)) })),
        styles: p.styles.map((s) => ({ kind: 'style', name: s.data.name ?? s.id, fm: s.data, body: s.body })),
      };
    });
}

