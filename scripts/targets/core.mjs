// ------------------------------------------------------------------ shared helpers for agent-like outputs
// Rewrites an agent body for a target and prepends the skill-preload line and (optionally) a read-only note, because
// most targets cannot preload skills or enforce read-only roles in frontmatter.
export function agentBodyFor(plugin, agent, dialect, { preloadLine, readOnlyNote } = {}) {
  let body = rewrite(agent.body.replace(/^\s+/, ''), plugin, dialect, { from: 'agent' });
  const skills = agent.fm.skills ? [].concat(agent.fm.skills) : [];
  if (skills.length && preloadLine) body = `${preloadLine(skills)}\n\n${body}`;
  if (agent.readOnly && readOnlyNote) body = `${readOnlyNote}\n\n${body}`;
  return body;
}

