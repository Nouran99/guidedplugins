// ------------------------------------------------------------------ rewriting
// A dialect describes how a target spells references and paths. Reference functions return a string.
// Path functions return { path } (a file path, wrapped in backticks when the source had them) or { phrase } (prose,
// never backticked), because agents have no fixed install location and must be told to "load the skill" instead.
// ctx = { from: 'skill' | 'agent' | 'doc', skill?: <name of the skill being written> }.
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\-]/g, '\\$&');

function pathOut(res, b1, b2) {
  if (res.phrase !== undefined) return res.phrase;
  return b1 && b2 ? `\`${res.path}\`` : `${b1}${res.path}${b2}`;
}

export function rewrite(text, plugin, d, ctx) {
  const slug = esc(plugin.slug);
  const kinds = {
    skill: new Set(plugin.skills.map((x) => x.name)),
    agent: new Set(plugin.agents.map((x) => x.name)),
    style: new Set(plugin.styles.map((x) => x.name)),
  };
  let t = text;

  // descriptive mentions of a rule file ("comes from `references/mini.md`") point at the hub's file, so resolve them from siblings and agents
  if (ctx.from === 'agent' || (ctx.from === 'skill' && ctx.skill !== 'principles')) {
    t = t.replace(/`references\/(full|mini|nano)\.md`/g, (m, r) => pathOut(d.refFile(plugin, r, ctx), '`', '`'));
  }

  // "Read `<path to a skill>`" -> either "Read `<relative path>`" or "Load the `<skill>` skill"
  t = t.replace(/Read (`?)\$\{CLAUDE_PLUGIN_ROOT\}\/skills\/([a-z0-9-]+)\/SKILL\.md(`?)/g, (m, b1, n, b2) => d.readSkill(plugin, n, ctx, b1 && b2));
  t = t.replace(/(`?)\$\{CLAUDE_PLUGIN_ROOT\}\/skills\/([a-z0-9-]+|<[a-z-]+>)\/SKILL\.md(`?)/g, (m, b1, n, b2) => pathOut(d.skillFile(plugin, n, ctx), b1, b2));
  t = t.replace(/(`?)\$\{CLAUDE_PLUGIN_ROOT\}\/skills\/principles\/references\/(full|mini|nano)\.md(`?)/g, (m, b1, r, b2) => pathOut(d.refFile(plugin, r, ctx), b1, b2));
  t = t.replace(/(`?)\$\{CLAUDE_SKILL_DIR\}\/references\/(full|mini|nano)\.md(`?)/g, (m, b1, r, b2) => pathOut(d.refFile(plugin, r, ctx), b1, b2));
  t = t.replace(/(`?)\$\{CLAUDE_PLUGIN_ROOT\}\/skills\/(`?)/g, (m, b1, b2) => pathOut(d.skillsDir(plugin, ctx), b1, b2));
  t = t.replace(/(`?)\$\{CLAUDE_PLUGIN_ROOT\}\/docs\/DESIGN\.md(`?)/g, (m, b1, b2) => pathOut(d.designFile(plugin, ctx), b1, b2));

  // references: one pass so replacements are never re-scanned
  const re = new RegExp(`(?<![\\w$-])(\\/output-style )?(\\/|@agent-)?${slug}:([a-z][a-z0-9]*(?:-[a-z0-9]+)*)`, 'g');
  t = t.replace(re, (m, outStyle, slash, name) => {
    if (outStyle) return kinds.style.has(name) ? d.refStyle(plugin, name, ctx) : m;
    if (slash === '/') return kinds.skill.has(name) ? d.refSkill(plugin, name, ctx) : m;
    if (kinds.agent.has(name)) return d.refAgent(plugin, name, ctx);
    if (kinds.skill.has(name)) return d.refSkill(plugin, name, ctx);
    if (kinds.style.has(name)) return d.refStyle(plugin, name, ctx);
    return m;
  });

  // plain backticked mentions of a sibling agent or hyphenated skill, written without the plugin prefix ("is `test-gap-reviewer`")
  const hyphSkills = new Set([...kinds.skill].filter((n) => n.includes('-') && !kinds.agent.has(n)));
  t = t.replace(/`([a-z][a-z0-9]*(?:-[a-z0-9]+)*)`/g, (m, n) => {
    if (kinds.agent.has(n)) return `\`${d.refAgent(plugin, n, ctx)}\``;
    if (hyphSkills.has(n)) return `\`${d.refSkill(plugin, n, ctx)}\``;
    return m;
  });

  // bare hyphenated agent names (in fenced output templates: "Not checked: missing tests (test-gap-reviewer)").
  // Agent names are distinctive; hyphenated skill names are not ("error-handling" is also plain English), so skills are left alone.
  const hyphAgents = [...kinds.agent].filter((n) => n.includes('-')).sort((a, b) => b.length - a.length);
  if (hyphAgents.length) {
    const bare = new RegExp(`(?<![\\w\\-/:\`.$])(${hyphAgents.map(esc).join('|')})(?![\\w\\-\`])`, 'g');
    t = t.replace(bare, (m, n) => d.refAgent(plugin, n, ctx));
  }

  // arguments
  t = t.replace(/^Arguments: `\$ARGUMENTS`[ \t]*$/gm, `Arguments: ${d.argsLine}`);
  t = t.replace(/`\$ARGUMENTS`/g, d.argsInline).replace(/\$ARGUMENTS/g, d.argsInline);
  return t;
}

// Constructs that must not survive in a non-Claude target.
export function leftovers(text, slugs, { mentions = false } = {}) {
  const found = [];
  if (mentions) text = text.replace(new RegExp(`\\$(?:${slugs.map(esc).join('|')}):[a-z][a-z0-9-]*`, 'g'), ''); // Codex "$plugin:skill" mentions are the intended syntax
  if (/\$\{CLAUDE_[A-Z_]+\}/.test(text)) found.push('${CLAUDE_*} variable');
  if (/\$ARGUMENTS/.test(text)) found.push('$ARGUMENTS');
  if (/\/output-style\b/.test(text)) found.push('/output-style');
  const refs = new RegExp(`(?<![\\w-])\\/?(${slugs.map(esc).join('|')}):[a-z][a-z0-9-]*`, 'g');
  const m = text.match(refs);
  if (m) found.push(`unrewritten reference ${m[0]}`);
  return found;
}

// ------------------------------------------------------------------ frontmatter / files
export const q = (s) => JSON.stringify(String(s)); // JSON strings are valid YAML double-quoted scalars

export function frontmatter(fields) {
  const lines = ['---'];
  for (const [k, v] of Object.entries(fields)) {
    if (v === undefined || v === null) continue;
    if (typeof v === 'boolean' || typeof v === 'number') lines.push(`${k}: ${v}`);
    else if (Array.isArray(v)) { lines.push(`${k}:`); for (const x of v) lines.push(`  - ${q(x)}`); }
    else if (typeof v === 'object') { lines.push(`${k}:`); for (const [kk, vv] of Object.entries(v)) lines.push(`  ${kk}: ${q(vv)}`); }
    else lines.push(`${k}: ${q(v)}`);
  }
  lines.push('---', '');
  return lines.join('\n');
}

export function writeFile(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text.endsWith('\n') ? text : `${text}\n`);
}

export function copyFile(src, dst) {
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.copyFileSync(src, dst);
}

export function cleanDir(dir) { fs.rmSync(dir, { recursive: true, force: true }); }

export function descriptionFor(skill, suffix = '') {
  const base = String(skill.fm.description ?? '').trim();
  return suffix ? `${base} ${suffix}`.trim() : base;
}

